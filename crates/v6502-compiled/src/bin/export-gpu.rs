//! The rung 2 kernel for a browser: `web/gpu.json`.
//!
//!     cargo run --release -p v6502-compiled --bin export-gpu -- web/gpu.json
//!
//! One file carrying everything a WebGPU host needs to run the kernel the
//! way `v6502-gpu` runs it natively: the WGSL text, the tables its bind
//! groups hold (gates, switches, junctions, offsets), the counts the
//! params uniform wants, and the few signal ids the host consults (the
//! clock it tracks, the pins a page may sample). The swarm page is the
//! consumer.
//!
//! Derived from the CC BY-NC-SA die data like everything the kernel is
//! built from: generated, gitignored, never committed.

use std::fmt::Write as _;

fn nums<T: std::fmt::Display>(v: impl IntoIterator<Item = T>) -> String {
    let mut s = String::new();
    for (i, x) in v.into_iter().enumerate() {
        if i > 0 {
            s.push(',');
        }
        let _ = write!(s, "{x}");
    }
    s
}

fn escape(text: &str) -> String {
    let mut s = String::with_capacity(text.len() + 64);
    for c in text.chars() {
        match c {
            '"' => s.push_str("\\\""),
            '\\' => s.push_str("\\\\"),
            '\n' => s.push_str("\\n"),
            c if (c as u32) < 0x20 => {
                let _ = write!(s, "\\u{:04x}", c as u32);
            }
            c => s.push(c),
        }
    }
    s
}

fn main() {
    let out = std::env::args().nth(1).unwrap_or_else(|| "web/gpu.json".into());
    use v6502_compiled::kernel;
    let mut s = String::with_capacity(kernel::SWITCH_TABLE.len() * 8 + v6502_compiled::KERNEL_WGSL.len() + 4096);
    s.push_str("{\"_\":\"The rung 2 kernel and its tables, for a WebGPU host. Generated by export-gpu from the die data (CC BY-NC-SA); do not edit.\"");
    let _ = write!(s, ",\"nodes\":{},\"trans\":{},\"max_rounds\":{},\"lanes_per_word\":32", kernel::NODES, kernel::TRANS, v6502_compiled::MAX_ROUNDS);
    let _ = write!(s, ",\"folded_gates\":{},\"junctions\":{}", kernel::FOLDED_GATES, kernel::JUNCTIONS);
    let _ = write!(
        s,
        ",\"sig\":{{\"clk0\":{},\"rw\":{},\"sync\":{},\"ab\":[{}],\"db\":[{}]}}",
        kernel::sig::CLK0,
        kernel::sig::RW,
        kernel::sig::SYNC,
        nums(kernel::sig::AB),
        nums(kernel::sig::DB)
    );
    let _ = write!(s, ",\"gate_of\":[{}]", nums(kernel::GATE_OF.iter().map(|&g| g as u32)));
    let _ = write!(s, ",\"switch_table\":[{}]", nums(kernel::SWITCH_TABLE.iter()));
    let _ = write!(s, ",\"gate_table\":[{}]", nums(kernel::GATE_TABLE.iter()));
    let _ = write!(s, ",\"junction_table\":[{}]", nums(kernel::JUNCTION_TABLE.iter()));
    let _ = write!(s, ",\"gate_offsets\":[{}]", nums(kernel::GATE_OFFSETS.iter()));
    let _ = write!(s, ",\"junction_offsets\":[{}]", nums(kernel::JUNCTION_OFFSETS.iter()));
    let _ = write!(s, ",\"wgsl\":\"{}\"}}", escape(v6502_compiled::KERNEL_WGSL));
    std::fs::write(&out, &s).expect("write gpu.json");
    println!("export-gpu: {} ({} bytes: {} switches, {} gate words, wgsl {} chars)", out, s.len(), kernel::SWITCH_TABLE.len() / 4, kernel::GATE_TABLE.len(), v6502_compiled::KERNEL_WGSL.len());
}
