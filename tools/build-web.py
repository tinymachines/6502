#!/usr/bin/env python3
"""Produce a content-hashed, offline-capable build of web/ into dist/.

    python3 tools/build-web.py web dist

Why this exists: a service worker that caches aggressively is only safe if a
given URL's contents can never change. Hashing every asset makes that true, and
makes `immutable` caching honest. Without it a cache-first worker will
eventually pair a new .wasm with an old app.js, which fails in ways that look
like corruption rather than staleness.

Hashing is done dependency-first, so a change to a leaf ripples all the way up:

    layout.bin ─┐
    *_bg.wasm ──┴─> v6502_wasm.js ─┐
    renderer.js ──┬─────────────── ┼─> app.js ─┐
    disasm.js ────┤                ┘           ├─> index.html
    lab.js ───────┘                            │
    style.css, icons ──> manifest.webmanifest ─┤
    site-nav.js, version-footer.js ────────────┘

index.html and sw.js are deliberately NOT hashed: they are the entry points, and
are served no-cache so a deploy takes effect immediately.
"""

